name = "Zatchbell"
nameshort = len(name)
print(nameshort)
s1 = name[0:3] # starts from 0 and ends at 3-1
print(s1)
s2 = name[3:6] # starts from 3 and ends at 6-1
print(s2)
s3 = name[1] # starts from 1 and ends at 1
print(s3)

#negative indexing
s4 = name[-1] # starts from -1 and ends at -1   
print(s4)   
s5 = name[-4:-1]
print(s5)   
print(name[1:4])
print(name[:4]) # starts from 0 and ends at 4-1
print(name[1:]) # starts from 1 and ends at the end of the string
print(name[:]) # starts from 0 and ends at the end of the string


